-- NexProxy order payment, inventory, assignment and fulfillment backend.
-- Admin operations are restricted through public.is_admin() (mamunfb13@gmail.com).

create table if not exists public.proxy_inventory (
    id uuid primary key default gen_random_uuid(),
    proxy_name text not null,
    proxy_number text not null,
    status text not null default 'AVAILABLE' check (status in ('AVAILABLE','ASSIGNED','DISABLED')),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (proxy_name), unique (proxy_number)
);

create table if not exists public.proxy_assignments (
    id uuid primary key default gen_random_uuid(),
    order_id text not null references public.orders(order_id) on delete cascade,
    inventory_id uuid references public.proxy_inventory(id) on delete set null,
    proxy_nickname text not null,
    proxy_number text not null,
    host text,
    port text,
    assignment_type text not null check (assignment_type in ('ASSIGNED','TRIAL')),
    status text not null default 'ACTIVE' check (status in ('ACTIVE','EXPIRED','REPLACED')),
    duration_days integer not null check (duration_days > 0),
    extension_days integer not null default 0 check (extension_days >= 0),
    start_at timestamptz not null default now(),
    expires_at timestamptz not null,
    replaced_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create index if not exists proxy_assignments_order_created_idx on public.proxy_assignments(order_id, created_at desc);
create unique index if not exists proxy_assignments_one_active_order_idx on public.proxy_assignments(order_id) where status='ACTIVE';

create table if not exists public.proxy_fulfillments (
    id uuid primary key default gen_random_uuid(),
    order_id text not null unique references public.orders(order_id) on delete cascade,
    status text not null default 'NOT_ASSIGNED' check (status in ('NOT_ASSIGNED','ASSIGNED','DELIVERED')),
    proxy_assigned boolean not null default false,
    delivery_method text,
    proxy_reference text,
    assigned_at timestamptz,
    delivered_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.payment_settings (
    id integer generated by default as identity primary key,
    wallet_address text not null default '',
    enabled boolean not null default false,
    updated_by uuid references auth.users(id),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
insert into public.payment_settings (wallet_address, enabled)
select '', false where not exists (select 1 from public.payment_settings);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('payment-proofs', 'payment-proofs', false, 5242880, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=false, file_size_limit=5242880,
    allowed_mime_types=array['image/jpeg','image/png','image/webp'];

create table if not exists public.admin_activity_log (
    id uuid primary key default gen_random_uuid(),
    admin_id uuid references auth.users(id),
    action text not null,
    entity_type text,
    entity_id text,
    details jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);
create index if not exists admin_activity_log_created_idx on public.admin_activity_log(created_at desc);

create table if not exists public.payment_proofs (
    id uuid primary key default gen_random_uuid(),
    order_id text not null references public.orders(order_id) on delete cascade,
    customer_id uuid not null references auth.users(id) on delete cascade,
    bucket_id text not null default 'payment-proofs',
    object_path text not null unique,
    mime_type text not null check (mime_type in ('image/jpeg','image/png','image/webp')),
    size_bytes integer not null check (size_bytes between 1 and 5242880),
    created_at timestamptz not null default now()
);
create index if not exists payment_proofs_order_idx on public.payment_proofs(order_id, created_at desc);

