create or replace function public.get_admin_payment_settings()
returns setof public.payment_settings language plpgsql stable security definer set search_path=public,pg_temp as $$
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 return query select * from public.payment_settings order by id limit 1;
end $$;

create or replace function public.update_payment_settings(p_wallet_address text, p_enabled boolean)
returns setof public.payment_settings language plpgsql security definer set search_path=public,pg_temp as $$
declare v_row public.payment_settings;
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 if length(btrim(coalesce(p_wallet_address,''))) not between 20 and 128 then raise exception using errcode='22023', message='Invalid wallet address length.'; end if;
 update public.payment_settings set wallet_address=btrim(p_wallet_address),enabled=coalesce(p_enabled,false),updated_by=auth.uid(),updated_at=now() where id=(select min(id) from public.payment_settings) returning * into v_row;
 if not found then insert into public.payment_settings(wallet_address,enabled,updated_by) values (btrim(p_wallet_address),coalesce(p_enabled,false),auth.uid()) returning * into v_row; end if;
 return next v_row;
end $$;

create or replace function public.get_admin_fulfillment_status()
returns setof public.proxy_fulfillments language plpgsql stable security definer set search_path=public,pg_temp as $$
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 return query select * from public.proxy_fulfillments order by created_at desc;
end $$;

create or replace function public.verify_payment(p_order_id text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_order public.orders;
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 update public.orders set payment_status='PAYMENT_VERIFIED', payment_verified_at=now(), order_status='PAID', updated_at=now()
 where order_id=p_order_id and payment_status='PAYMENT_SUBMITTED' returning * into v_order;
 if not found then raise exception using errcode='P0002', message='Payment is not awaiting verification.'; end if;
 insert into public.admin_activity_log(admin_id,action,entity_type,entity_id,details) values(auth.uid(),'verify_payment','order',p_order_id,jsonb_build_object('payment_method',v_order.payment_method));
 return jsonb_build_object('success',true,'order_id',p_order_id,'payment_status',v_order.payment_status);
end $$;

create or replace function public.create_proxy_assignment(
 p_order_id text,p_proxy_nickname text,p_proxy_number text,p_host text,p_port text,p_assignment_type text,p_duration_days integer
) returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_order public.orders; v_inventory public.proxy_inventory; v_assignment public.proxy_assignments;
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 if p_assignment_type not in ('ASSIGNED','TRIAL') or p_duration_days is null or p_duration_days<1 or p_duration_days>3650 then raise exception using errcode='22023', message='Invalid assignment details.'; end if;
 select * into v_order from public.orders where order_id=p_order_id for update;
 if not found then raise exception using errcode='P0002', message='Order not found.'; end if;
 if v_order.payment_status not in ('PAYMENT_VERIFIED','NO_PAYMENT_REQUIRED') then raise exception using errcode='22023', message='Payment must be verified before assigning a proxy.'; end if;
 if exists(select 1 from public.proxy_assignments where order_id=p_order_id and status='ACTIVE') then raise exception using errcode='23505', message='Order already has an active proxy assignment.'; end if;
 select * into v_inventory from public.proxy_inventory where status='AVAILABLE' and (proxy_number=btrim(p_proxy_number) or proxy_name=btrim(p_proxy_nickname)) for update;
 if not found then raise exception using errcode='P0002', message='Available proxy inventory not found. Add the proxy to inventory first.'; end if;
 update public.proxy_inventory set status='ASSIGNED',updated_at=now() where id=v_inventory.id;
 insert into public.proxy_assignments(order_id,inventory_id,proxy_nickname,proxy_number,host,port,assignment_type,duration_days,start_at,expires_at)
 values(p_order_id,v_inventory.id,v_inventory.proxy_name,v_inventory.proxy_number,nullif(btrim(p_host),''),nullif(btrim(p_port),''),p_assignment_type,p_duration_days,now(),now()+make_interval(days=>p_duration_days)) returning * into v_assignment;
 insert into public.proxy_fulfillments(order_id,status,proxy_assigned,proxy_reference,assigned_at)
 values(p_order_id,'ASSIGNED',true,v_assignment.proxy_number,v_assignment.start_at)
 on conflict(order_id) do update set status='ASSIGNED',proxy_assigned=true,proxy_reference=excluded.proxy_reference,assigned_at=excluded.assigned_at,updated_at=now();
 update public.orders set order_status='FULFILLING',updated_at=now() where order_id=p_order_id;
 insert into public.admin_activity_log(admin_id,action,entity_type,entity_id,details) values(auth.uid(),'create_proxy_assignment','order',p_order_id,jsonb_build_object('assignment_id',v_assignment.id,'proxy_number',v_assignment.proxy_number));
 return jsonb_build_object('success',true,'assignment_id',v_assignment.id);
end $$;

create or replace function public.extend_proxy_assignment(p_assignment_id uuid,p_extension_days integer,p_reason text default null)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_assignment public.proxy_assignments;
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 if p_extension_days not between 1 and 365 then raise exception using errcode='22023', message='Extension days must be between 1 and 365.'; end if;
 update public.proxy_assignments set expires_at=greatest(expires_at,now())+make_interval(days=>p_extension_days),extension_days=extension_days+p_extension_days,updated_at=now()
 where id=p_assignment_id and status='ACTIVE' returning * into v_assignment;
 if not found then raise exception using errcode='P0002', message='Active proxy assignment not found.'; end if;
 insert into public.admin_activity_log(admin_id,action,entity_type,entity_id,details) values(auth.uid(),'extend_proxy_assignment','assignment',p_assignment_id::text,jsonb_build_object('days',p_extension_days,'reason',left(coalesce(p_reason,''),500)));
 return jsonb_build_object('success',true,'assignment_id',v_assignment.id,'expires_at',v_assignment.expires_at);
end $$;

create or replace function public.replace_proxy_assignment(p_assignment_id uuid,p_proxy_nickname text,p_proxy_number text,p_host text,p_port text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_old public.proxy_assignments; v_new public.proxy_inventory; v_id uuid;
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 select * into v_old from public.proxy_assignments where id=p_assignment_id and status='ACTIVE' for update;
 if not found then raise exception using errcode='P0002', message='Active proxy assignment not found.'; end if;
 select * into v_new from public.proxy_inventory where status='AVAILABLE' and (proxy_number=btrim(p_proxy_number) or proxy_name=btrim(p_proxy_nickname)) for update;
 if not found then raise exception using errcode='P0002', message='Available proxy inventory not found. Add the proxy to inventory first.'; end if;
 update public.proxy_inventory set status='AVAILABLE',updated_at=now() where id=v_old.inventory_id;
 update public.proxy_inventory set status='ASSIGNED',updated_at=now() where id=v_new.id;
 update public.proxy_assignments set status='REPLACED',replaced_at=now(),updated_at=now() where id=v_old.id;
 insert into public.proxy_assignments(order_id,inventory_id,proxy_nickname,proxy_number,host,port,assignment_type,status,duration_days,extension_days,start_at,expires_at)
 values(v_old.order_id,v_new.id,v_new.proxy_name,v_new.proxy_number,nullif(btrim(p_host),''),nullif(btrim(p_port),''),v_old.assignment_type,'ACTIVE',v_old.duration_days,v_old.extension_days,now(),greatest(v_old.expires_at,now())) returning id into v_id;
 update public.proxy_fulfillments set status='ASSIGNED',proxy_assigned=true,proxy_reference=v_new.proxy_number,assigned_at=now(),updated_at=now() where order_id=v_old.order_id;
 insert into public.admin_activity_log(admin_id,action,entity_type,entity_id,details) values(auth.uid(),'replace_proxy_assignment','assignment',p_assignment_id::text,jsonb_build_object('replacement_id',v_id,'proxy_number',v_new.proxy_number));
 return jsonb_build_object('success',true,'assignment_id',v_id);
end $$;

create or replace function public.repair_proxy_fulfillment(p_order_id text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_assignment public.proxy_assignments; v_fulfillment public.proxy_fulfillments;
begin
 if not public.is_admin() then raise exception using errcode='42501', message='Admin access required.'; end if;
 select * into v_assignment from public.proxy_assignments where order_id=p_order_id and status='ACTIVE' order by created_at desc limit 1;
 if not found then raise exception using errcode='P0002', message='Active proxy assignment not found.'; end if;
 if not exists(select 1 from public.proxy_inventory where id=v_assignment.inventory_id) then raise exception using errcode='P0002', message='Active assignment proxy is missing from inventory.'; end if;
 if exists(select 1 from public.proxy_inventory where id=v_assignment.inventory_id and status<>'ASSIGNED') then raise exception using errcode='22023', message='Active assignment proxy inventory is not ASSIGNED.'; end if;
 select * into v_fulfillment from public.proxy_fulfillments where order_id=p_order_id;
 if found and v_fulfillment.status='DELIVERED' then raise exception using errcode='22023', message='Delivered fulfillment cannot be repaired.'; end if;
 if found and v_fulfillment.status='ASSIGNED' and v_fulfillment.proxy_assigned and v_fulfillment.proxy_reference=v_assignment.proxy_number and v_fulfillment.assigned_at=v_assignment.start_at then raise exception using errcode='22023', message='Fulfillment is already synchronized.'; end if;
 insert into public.proxy_fulfillments(order_id,status,proxy_assigned,proxy_reference,assigned_at)
 values(p_order_id,'ASSIGNED',true,v_assignment.proxy_number,v_assignment.start_at)
 on conflict(order_id) do update set status='ASSIGNED',proxy_assigned=true,proxy_reference=excluded.proxy_reference,assigned_at=excluded.assigned_at,updated_at=now();
 insert into public.admin_activity_log(admin_id,action,entity_type,entity_id) values(auth.uid(),'repair_proxy_fulfillment','order',p_order_id);
 return jsonb_build_object('success',true,'order_id',p_order_id);
end $$;

